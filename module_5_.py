import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from tqdm.notebook import tqdm
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier

flights_07 = pd.read_csv("flight_delays_2025_07.csv")
flights_08 = pd.read_csv("flight_delays_2025_08.csv")
flights_09 = pd.read_csv("flight_delays_2025_09.csv")
flights_10 = pd.read_csv("flight_delays_2025_10.csv")
flights_11 = pd.read_csv("flight_delays_2025_11.csv")
flights_12 = pd.read_csv("flight_delays_2025_12.csv")

flights = pd.concat([
    flights_07,
    flights_08,
    flights_09,
    flights_10,
    flights_11,
    flights_12
], ignore_index=True)

print("Total Flights:", len(flights))

flights.head()

flights = flights.dropna(subset=["ArrDel15"])

features = [
    "Month",
    "DayofMonth",
    "DayOfWeek",
    "CRSDepTime",
    "CRSArrTime",
    "CRSElapsedTime",
    "Distance"
]

flights = flights.dropna(subset=features)

print("Flights with known arrival delay:", len(flights))

flights.groupby("ArrDel15").size()

X = flights[features]
y = flights["ArrDel15"]

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.2, random_state=31337
)

print(X_train.shape, X_test.shape)

def flight_accuracy(model, X, y):
    predicted_delays = model.predict(X)

    correct_delays = [
        1 if predicted_delay == actual_delay else 0
        for predicted_delay, actual_delay in zip(predicted_delays, y)
    ]

    return sum(correct_delays) / len(correct_delays)


tree_rows = []

for depth in tqdm(range(1, 11)):
    model = DecisionTreeClassifier(max_depth=depth, random_state=31337)
    model.fit(X_train, y_train)

    train_acc = flight_accuracy(model, X_train, y_train)
    test_acc = flight_accuracy(model, X_test, y_test)

    tree_rows.append({
        "depth": depth,
        "train_acc": train_acc,
        "test_acc": test_acc
    })

tree_df = pd.DataFrame(tree_rows)

tree_df

tree_df.plot(
    x="depth",
    y=["train_acc", "test_acc"],
    marker="o",
    ylabel="Accuracy",
    xlabel="Max Depth"
)

predicted_delays = model.predict(X_test)

wrong_rows = []

for flight_id, predicted_delay, actual_delay in zip(X_test.index, predicted_delays, y_test):
    if predicted_delay != actual_delay:
        wrong_rows.append({
            "flight_id": flight_id,
            "actual": actual_delay,
            "predicted": predicted_delay
        })

wrong_df = pd.DataFrame(wrong_rows)

wrong_df.head(5)

